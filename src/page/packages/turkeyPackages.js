const getHotelPackageName = (groupInfo, row) => {
  const hotelText = String(row.hotel || "")
    .replace(/\s*\+\s*/g, " + ")
    .replace(/\s+/g, " ")
    .trim();

  return `${groupInfo.title}: ${hotelText}`;
};

